package io.github.yuloong07star.luwi.ui

/**
 * 网页里那一层"盖住会话"的东西与系统返回键之间唯一的一根线
 *
 * **为什么不是一个 `BackHandler`**: 返回键只有 [LuwiApp] 那一处接得住 —— 它的 `BackHandler` 排在
 * `NavDisplay` 后面, 按 LIFO 后登记的先赢, 页面里再登记一个永远轮不到 (2026-10-08 设置页上"按返回
 * 什么都不发生"就是这条)。所以那一处按返回时先问这里一句, 而这一句是异步的: 页面的状态只有
 * `evaluateJavascript` 问得到
 *
 * **回调式而不是返回布尔**: 手机上点一条网页链接, dsh 会把它开在右栏那个浏览器格里, 而视口窄于
 * 768 px 时那一格是**全屏**的 —— 会话连同顶栏一起被盖住 (2026-10-18 主人报的就是这个: "网页全屏,
 * 无法返回会话", 那时按返回只会弹「再按一次退出」)。页面收得掉这一层就收掉, 收不掉 (没展开、或者
 * 页面没答话) 必须把这一下**还回去**, 否则主页的「再按一次退出」就废了 —— 于是这里传的是"没事时
 * 做什么", 而不是一个布尔
 */
object PageBack {

    /**
     * 页面现在接不接得住返回键: 接住了就什么都不回话, 没接住就调 `nothing`
     *
     * `null` = 主页那块 WebView 没在看 (设置页开着 / host 还没起来), 那一下直接归 [LuwiApp]
     */
    var handle: ((nothing: () -> Unit) -> Unit)? = null
}
